#!/usr/bin/env node
// Regenerates the fixture client report and re-test comparison in docs/fixture-sample-* from the
// fixture runs in examples/sample-runs/, through the same code `hornet-swarm client-report` runs.
// Nothing is fetched. The live sample, docs/sample-*-toolshop-live.*, is a real Toolshop run and
// is not written here.
//
//   pnpm build && node scripts/generate-sample-report.mjs           # write the docs
//   node scripts/generate-sample-report.mjs --check                 # exit 1 if the docs are stale
//
// The fixture runs are written to a private temporary home, which is removed afterwards.
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { CHECKOUT_FAILURE_TEXT, accessibilityFile, sampleRuns } from '../examples/sample-runs/toolshop-live-sample-runs.mjs';

const root = join(import.meta.dirname, '..');
const dist = (pkg) => pathToFileURL(join(root, 'packages', pkg, 'dist', 'index.js')).href;
for (const pkg of ['core', 'report', 'controller']) {
  if (!existsSync(join(root, 'packages', pkg, 'dist', 'index.js'))) {
    process.stderr.write(`packages/${pkg} is not built. Run pnpm build first.\n`);
    process.exit(2);
  }
}
const core = await import(dist('core'));
const report = await import(dist('report'));
const controller = await import(dist('controller'));

// The files docs/sample-*-toolshop-live.* are a real live Toolshop run, copied from that run.
// They are not regenerated from the fixture, so a later fixture change cannot overwrite them.
export const OUTPUTS = {
  'docs/fixture-sample-client-report.md': (first, second) => second.markdown,
  'docs/fixture-sample-client-report.html': (first, second) => readFileSync(second.paths.html, 'utf8'),
  'docs/fixture-sample-retest-diff.md': (first, second, diff) => diff.markdown,
};

const SAMPLE_NOTE = [
  '<!-- Generated by scripts/generate-sample-report.mjs from the fixture runs in examples/sample-runs/.',
  '     They are made from findings the harness recorded on Toolshop; the target-size finding and the',
  '     changes between the two runs are illustrative. Do not edit by hand. -->',
  '',
].join('\n');

function writeFixtureHome(home) {
  for (const dir of ['projects/toolshop-live', 'authorisations', 'runs']) core.privateDir(join(home, dir));
  core.writePrivateFile(join(home, 'projects/toolshop-live/project.yaml'), readFileSync(join(root, 'examples/projects/toolshop-live/project.yaml'), 'utf8'));
  core.writePrivateFile(join(home, 'authorisations/toolshop-live-practice.yaml'), readFileSync(join(root, 'examples/authorisations/toolshop-live-practice.yaml'), 'utf8'));
  for (const run of sampleRuns()) {
    const runDir = core.privateDir(join(home, 'runs', run.runId));
    const failed = run.users.some((user) => user.journeys.some((journey) => journey.status === 'fail'));
    const steps = run.users.flatMap((user) => user.journeys.flatMap((journey) => journey.steps));
    const result = core.runResultSchema.parse({
      schema_version: '1',
      run_id: run.runId,
      project: 'toolshop-live',
      started_at: run.startedAt,
      finished_at: run.finishedAt,
      status: failed ? 'failed' : 'passed',
      gate: 'per_user',
      gate_passed: true,
      totals: {
        users: run.users.length,
        journeys: run.users.reduce((sum, user) => sum + user.journeys.length, 0),
        steps: steps.length,
        passed: steps.filter((entry) => entry.status === 'pass').length,
        failed: steps.filter((entry) => entry.status === 'fail').length,
        skipped: 0,
      },
      users: run.users.map((user) => ({ label: user.label, phase1: user.phase1, journeys: user.journeys.map(({ name: _name, ...journey }) => journey) })),
      environment: 'test',
      authorisation_id: 'toolshop-live-practice',
      redaction: 'pass',
    });
    const analysis = report.buildAnalysis({ result, users: run.users, chaos: null, suspected: '', confidence: 0, repro: [], regressions: [], next: [] });
    core.writePrivateFile(join(runDir, 'run.json'), `${JSON.stringify(result, null, 2)}\n`);
    core.writePrivateFile(join(runDir, 'analysis.json'), `${JSON.stringify(analysis, null, 2)}\n`);
    core.writePrivateFile(join(runDir, 'summary.md'), report.summaryMarkdown(run.users, result.status));
    for (const user of run.users) {
      for (const journey of user.journeys) {
        const journeyDir = core.privateDir(join(runDir, user.label, journey.id));
        for (const entry of journey.steps) {
          if (entry.accessibility) core.writePrivateFile(join(journeyDir, `accessibility-${entry.accessibility.name}.json`), accessibilityFile(entry.accessibility));
          if (entry.status === 'fail') core.writePrivateFile(join(journeyDir, `failed-step-${entry.index}.txt`), CHECKOUT_FAILURE_TEXT);
        }
      }
    }
  }
}

export function generate() {
  const home = core.privateTempDir('hornet-swarm-sample-');
  try {
    writeFixtureHome(home);
    const job = controller.loadClientJob(join(root, 'examples/jobs/toolshop-live-monthly.job.yaml'));
    const [firstRun, secondRun] = sampleRuns();
    const first = controller.writeClientReport({ job, runId: firstRun.runId, home });
    const second = controller.writeClientReport({ job, runId: secondRun.runId, home });
    const diff = controller.writeRetestDiff({ job, runId: secondRun.runId, home });
    if (!diff.diff) throw new Error(diff.reason);
    const files = {};
    for (const [path, pick] of Object.entries(OUTPUTS)) {
      const body = pick(first, second, diff);
      files[path] = path.endsWith('.md') ? `${SAMPLE_NOTE}${body}` : body;
    }
    return files;
  } finally {
    rmSync(home, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = generate();
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [path, body] of Object.entries(files)) {
    const target = join(root, path);
    if (check) {
      if (!existsSync(target) || readFileSync(target, 'utf8') !== body) stale.push(path);
    } else {
      writeFileSync(target, body);
      process.stdout.write(`${path}\n`);
    }
  }
  if (stale.length > 0) {
    process.stderr.write(`These sample files are out of date. Run node scripts/generate-sample-report.mjs:\n${stale.map((path) => `- ${path}`).join('\n')}\n`);
    process.exit(1);
  }
}
